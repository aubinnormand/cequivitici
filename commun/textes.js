/* Traduction. Les valeurs peuvent contenir des marqueurs {0}, {1}… remplacés par les
   arguments passés à l'appel. Une clé inconnue se renvoie elle-même, ce qui la rend visible
   à l'écran plutôt que de laisser un vide. */
const t = (cle, ...v) => {
  let x = (TEXTES[langue] && TEXTES[langue][cle]) || TEXTES.en[cle] || cle;
  v.forEach((val, i) => { x = x.replace('{' + i + '}', val); });
  return x;
};

