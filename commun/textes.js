/* Applique les traductions au document : texte pour data-t, invite de saisie pour data-tp,
   infobulle pour data-tt — ce dernier laissant le contenu de l'élément intact, ce qui permet
   de traduire un bouton réduit à une icône. */
function traduire() {
  document.documentElement.lang = langue;
  document.querySelectorAll('[data-t]').forEach(el => {
    const v = t(el.dataset.t); if (v) el.textContent = v;
  });
  document.querySelectorAll('[data-tp]').forEach(el => {
    const v = t(el.dataset.tp); if (v) el.placeholder = v;
  });
  document.querySelectorAll('[data-tt]').forEach(el => {
    const v = t(el.dataset.tt);
    if (v) { el.title = v; el.setAttribute('aria-label', v); }
  });
}

/* Changement de langue sans rechargement. Les textes du site basculent aussitôt ; seuls les
   noms vernaculaires viennent d'iNaturalist et doivent être redemandés — et uniquement si
   l'affichage les utilise. */
async function changerLangue(l) {
  if (!LANGUES[l] || l === langue) return;
  langue = l;
  try { localStorage.setItem('langue', l); } catch (e) { /* sans effet en navigation privée */ }

  MOIS = MOIS_L[l] || MOIS_L.en;
  MOIS_C = MOIS_C_L[l] || MOIS_C_L.en;
  traduire();

  majURL();

  // Les réponses en cache portent l'ancienne langue dans leur adresse : elles sont caduques.
  cache.clear();
  oublier();          // chaque module jette ce qu'il gardait dans l'ancienne langue

  if (!etat.especes.length) return;
  if (vue.nommage === 'sci') { redessinerTout(); return; }
  enTache(rafraichirNoms);
}

/* Ne récupère que les noms vernaculaires, par lots de deux cents taxons : environ sept
   requêtes pour un inventaire de mille quatre cents espèces, contre une cinquantaine pour
   un rechargement complet. */
async function rafraichirNoms() {
  const gen = generation;
  const ids = [...new Set([...etat.especes.map(e => e.id), ...etat.ancetres.keys()])];
  const parId = new Map(etat.especes.map(e => [e.id, e]));

  try {
    for (let i = 0; i < ids.length; i += 200) {
      progression(t('mNoms', Math.min(i + 200, ids.length), ids.length),
        (i / ids.length) * 100);
      const d = await appel('/taxa', { id: ids.slice(i, i + 200).join(','),
        per_page:200, locale:langue });
      verifier(gen);
      (d.results || []).forEach(x => {
        const nom = x.preferred_common_name || '';
        const e = parId.get(x.id);
        if (e) e.nomFr = nom;
        const a = etat.ancetres.get(x.id);
        if (a) a.nomFr = nom;
      });
    }
    redessinerTout();
    enregistrer();
    progression(t('mComplet'), null);
  } catch (e) {
    if (!(e instanceof Annule)) progression(t('mEchec', String((e && e.message) || e)), null);
  }
}


